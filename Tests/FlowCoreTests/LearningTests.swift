import Foundation
import FlowCore

enum LearningChecks {
    static func run() throws {
        let overlap = CGRect(x: 200, y: 150, width: 900, height: 700)
        let ownMain = WindowHitRegion(owner: 1, bounds: overlap)
        let document = WindowHitRegion(owner: 2, bounds: overlap)
        let pointer = CGPoint(x: 500, y: 400)
        precondition(WindowHitTesting.owner(at: pointer, windows: [document, ownMain]) == 2,
                     "A covered Float Translate window must not block lookup in a document")
        precondition(WindowHitTesting.owner(at: pointer, windows: [ownMain, document]) == 1)
        let ownCard = WindowHitRegion(owner: 1, bounds: CGRect(x: 480, y: 380, width: 100, height: 100))
        precondition(WindowHitTesting.owner(at: pointer, windows: [ownCard, document, ownMain]) == 1)
        precondition(WindowHitTesting.owner(at: CGPoint(x: 300, y: 250), windows: [ownCard, document, ownMain]) == 2)
        let transparent = WindowHitRegion(owner: 1, bounds: overlap, alpha: 0)
        precondition(WindowHitTesting.owner(at: pointer, windows: [transparent, document]) == 2)
        precondition(WindowHitTesting.owner(at: pointer, windows: []) == nil)
        print("WINDOW HIT TEST PASS: covered main window, foreground card, transparent and offscreen windows")
        let p = CGPoint(x: 10, y: 20), end = CGPoint(x: 90, y: 80), prefs = GesturePreferences()
        var gesture = LookupGestureMachine()
        _ = gesture.handle(.modifierDown(time: 1), preferences: prefs)
        precondition(gesture.handle(.modifierUp(time: 1.2, point: p), preferences: prefs).actions == [.lookup(p)])
        _ = gesture.handle(.modifierDown(time: 1), preferences: prefs)
        precondition(gesture.handle(.modifierUp(time: 10, point: p), preferences: prefs).actions == [.lookup(p)])
        _ = gesture.handle(.modifierDown(time: 2), preferences: prefs)
        _ = gesture.handle(.key, preferences: prefs)
        precondition(gesture.handle(.modifierUp(time: 2.2, point: p), preferences: prefs).actions.isEmpty)
        _ = gesture.handle(.modifierDown(time: 3), preferences: prefs)
        precondition(gesture.handle(.down(point: p, modified: true), preferences: prefs).consume)
        precondition(gesture.handle(.move(point: end), preferences: prefs).actions == [.beginArea(p), .updateArea(end)])
        precondition(gesture.handle(.up(point: end), preferences: prefs).actions == [.finishArea(end)])
        precondition(gesture.handle(.modifierUp(time: 3.2, point: p), preferences: prefs).actions.isEmpty)
        _ = gesture.handle(.down(point: p, modified: true), preferences: prefs)
        precondition(gesture.handle(.escape, preferences: prefs).actions == [.cancel])
        precondition(gesture.handle(.up(point: end), preferences: prefs).actions.isEmpty)
        let plain = GesturePreferences(plainClick: true)
        precondition(!gesture.handle(.down(point: p, modified: false), preferences: plain).consume)
        _ = gesture.handle(.move(point: end), preferences: plain)
        precondition(gesture.handle(.up(point: end), preferences: plain).actions.isEmpty)
        _ = gesture.handle(.down(point: p, modified: false), preferences: plain)
        precondition(gesture.handle(.up(point: p), preferences: plain).actions == [.lookup(p)])
        var hover = HoverGate()
        hover.move(to: p, now: 1)
        precondition(hover.ready(now: 1.5, delay: 0.75) == nil)
        precondition(hover.ready(now: 1.8, delay: 0.75) == p)
        precondition(hover.ready(now: 3, delay: 0.75) == nil)
        hover.move(to: end, now: 4)
        precondition(hover.ready(now: 4.5, delay: 0.75) == nil)
        precondition(hover.ready(now: 5, delay: 0.75) == end)
        let raw = #"{"word":"bank","meaning":"河岸\n岸边","language":"en","phonetic":"/bæŋk/"}"#
        let entry = try WordExplanation.parse(raw)
        precondition(entry.meaning == "河岸\n岸边" && entry.context.isEmpty)
        precondition(PartialJSON.string("meaning", in: #"{"word":"bank","meaning":"河岸\n"#) == "河岸\n")
        precondition(PartialJSON.string("meaning", in: #"{"meaning":"河\u5cb8"#) == "河岸")
        precondition(PartialJSON.string("meaning", in: #"{"meaning":"河\u5c"#) == "河")
        do { _ = try WordExplanation.parse(#"{"word":"bank"}"#); preconditionFailure("Missing meaning accepted") } catch {}
        let now = Date(timeIntervalSince1970: 1_700_000_000)
        var review = ReviewSchedule(now: now)
        review.review(.good, now: now)
        precondition(review.due == now.addingTimeInterval(86400))
        review.review(.good, now: review.due); precondition(review.intervalDays == 3)
        for _ in 0..<4 { review.review(.easy, now: review.due) }
        precondition(review.mastered)
        review.review(.again, now: now)
        precondition(review.due == now.addingTimeInterval(600) && review.repetitions == 0 && !review.mastered)
        let malicious = WordExplanation(word: "=SUM(1,2)", meaning: "\"quoted\"\nline", context: "<script>")
        let words = [VocabularyWord(explanation: malicious, target: "zh")]
        let csv = VocabularyExport.csv(words)
        precondition(csv.contains("\"'=SUM(1,2)\"") && csv.contains("\"\"quoted\"\""))
        precondition(VocabularyExport.html(malicious.context) == "&lt;script&gt;")
        precondition(VocabularyWord.identity(word: "café", language: "fr", target: "zh") != VocabularyWord.identity(word: "cafe", language: "fr", target: "zh"))
        precondition(InputKind.isWord("serendipity") && InputKind.isWord("state-of-the-art") && InputKind.isWord("getUserName"))
        precondition(!InputKind.isWord("The bank was covered with wild flowers.") && !InputKind.isWord("two\nlines") && !InputKind.isWord("123"))
        print("LEARNING CORE PASS: gesture tap/chord/drag/cancel/plain click, hover dwell/dedup, dictionary JSON, SRS, CSV escaping")
    }
}
